import { build } from 'esbuild'
import { mkdirSync, copyFileSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../', import.meta.url))
mkdirSync(root + 'systasys/server-dist', { recursive: true })
await build({
  entryPoints: [root + 'systasys/upstream-bridge.mjs'],
  outfile: root + 'systasys/server-dist/worlds-eye-upstream.cjs',
  bundle: true, platform: 'node', format: 'cjs', target: 'node22',
  minify: true, legalComments: 'inline',
  // Upstream msg() is an identity marker, not a translation. The source
  // policy imports only that marker; do not ship 3 MiB of browser locales
  // into a server parser. Refuse if upstream changes its semantics.
  plugins: [{ name: 'source-marker-only', setup(b) {
    b.onLoad({ filter: /src\/i18n\/index\.js$/ }, args => {
      const code = readFileSync(args.path, 'utf8')
      if (!/export function msg\(text\)\s*\{\s*return text;?\s*\}/.test(code)) throw Error('UPSTREAM_MSG_SEMANTICS_CHANGED')
      return { contents: 'export function msg(text) { return text }', loader: 'js' }
    })
  } }],
  banner: { js: '// Derived from monkidy/gods-eye-view upstream modules, MIT. See LICENSE_WORLDSEYE.md.\n// Generated by node systasys/build-upstream.mjs; no service, polling or source requests on import.' },
})
copyFileSync(root + 'LICENSE', root + 'systasys/server-dist/LICENSE_WORLDSEYE.md')
console.log('WORLDS_EYE_UPSTREAM_PARSERS_BUILD=PASS')
